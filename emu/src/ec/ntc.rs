//! The NTC table of firmware/ec (src/ntc_table.h): the vendor EC's own
//! conversion routine (bank 1 0xDD46: ADC code -> float degrees kelvin,
//! Beta 4250, 100K NTC under a 24K pull-up, 3.3 V, 10-bit) run on the
//! interpreter for every ADC code, then truncated as the vendor does
//! (whole degrees for its comparisons, tenths for what it writes to
//! CSU_PM). Port of scripts/open/ec_ntc_table.py (which needed numpy for
//! the single-precision add).
//!
//!   sky1emu ec-ntc-table VENDOR.bin OUT.h

use super::chip::Ec;
use super::cpu::{P1, PSW, SP};

const RET: u16 = 0xFFF0;

pub fn main(args: &[String]) -> i32 {
    if args.len() < 2 {
        eprintln!("usage: sky1emu ec-ntc-table VENDOR.bin OUT.h");
        return 2;
    }
    let img = match std::fs::read(crate::util::rooted(&args[0])) {
        Ok(d) => d,
        Err(e) => {
            eprintln!("{}: {e}", args[0]);
            return 2;
        }
    };
    let mut ec = Ec::new(&img, false, false, None);
    ec.run(120.0); // past the C start-up (RAM, initialised data)
    let mut vals = Vec::with_capacity(1024);
    for code in 0..1024u16 {
        ec.io.adc0 = Some(code);
        let c = &mut ec.cpu;
        c.sfr[SP as usize] = 0x30;
        c.sfr[P1 as usize] = (c.sfr[P1 as usize] & 0xF8) | 1; // bank 1
        c.push(RET as u8);
        c.push((RET >> 8) as u8);
        c.pc = 0xDD46;
        c.iram[7] = 0; // R7 = channel 0 (bank 0 registers)
        c.sfr[PSW as usize] = 0;
        c.sfr[0xA8] = 0; // no interrupts
        c.in_isr.clear();
        let mut n = 0u64;
        while ec.cpu.pc != RET {
            if let Err(h) = ec.cpu.step(&mut ec.io) {
                eprintln!("code {code}: {}", h.0);
                return 1;
            }
            n += 1;
            if n > 2_000_000 {
                eprintln!("stuck at {:04X}", ec.cpu.pc);
                return 1;
            }
        }
        let x = &ec.io.x;
        vals.push(f32::from_be_bytes([x[0x9638], x[0x9639], x[0x963A], x[0x963B]]));
    }
    let mut deg = Vec::with_capacity(1024);
    for &f in &vals {
        let mut c = (f + -273.5f32) as f64; // the vendor's FADD, in single precision
        if c.is_nan() || c.abs() > 1e6 {
            c = 0.0;
        }
        let d = c as i64; // truncation, as its float->int
        let t = if c >= 0.0 { ((c - d as f64) * 10.0) as i64 } else { 0 };
        deg.push((d.clamp(-128, 127), t));
    }
    let mut out = String::new();
    out.push_str("/* SPDX-License-Identifier: BSD-2-Clause-Patent */\n");
    out.push_str("/* generated by sky1emu ec-ntc-table (emu/src/ec/ntc.rs) from the vendor EC's own\n");
    out.push_str(" * conversion: ADC code -> degrees C (truncated), tenths */\n");
    out.push_str("static __code const int8_t ntc_deg[1024] = {\n");
    for row in deg.chunks(16) {
        out.push_str(&format!("\t{},\n", row.iter().map(|(d, _)| d.to_string()).collect::<Vec<_>>().join(", ")));
    }
    out.push_str("};\nstatic __code const uint8_t ntc_tenth[1024] = {\n");
    for row in deg.chunks(16) {
        out.push_str(&format!("\t{},\n", row.iter().map(|(_, t)| t.to_string()).collect::<Vec<_>>().join(", ")));
    }
    out.push_str("};\n");
    if let Err(e) = std::fs::write(&args[1], out) {
        eprintln!("{}: {e}", args[1]);
        return 1;
    }
    for code in [0x284u16, 0x2b6, 0x2e5, 0x2c9, 0x2f7, 0x2db, 0, 1, 1022, 1023] {
        println!("{code:#x} {} {:?}", vals[code as usize], deg[code as usize]);
    }
    0
}
