"""Generate PinMuxTableLib and GpioTableLib for a board from a vendor image.

The tables are register-level pad configuration recovered with iotables.py;
the surrounding library code follows the CIX Merak libraries.
"""

import argparse
import hashlib
import sys
import uuid
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from iotables import find_tables, gpio_lines, io_names, pinmux_lines  # noqa: E402

HDR = """/** @file
  {what} for {board}.

  Generated by scripts/extract/gen_iolibs.py from {src}
  (SHA-256 {sha}).
  Do not edit by hand; regenerate instead.

  SPDX-License-Identifier: BSD-2-Clause-Patent
**/
"""

PINMUX_C = """{hdr}
#include <Uefi.h>
#include <Library/BaseLib.h>
#include <Library/PinMuxTableLib.h>

PINMUX_CFG  *mPinMuxCfgTable;
UINT32      mPinMuxCfgTableLength;

PINMUX_CFG  PinMuxCfgTable[] = {{
{rows}
}};

RETURN_STATUS
EFIAPI
PinMuxTableLibConstructor (
  VOID
  )
{{
  mPinMuxCfgTable       = PinMuxCfgTable;
  mPinMuxCfgTableLength = ARRAY_SIZE (PinMuxCfgTable);

  return RETURN_SUCCESS;
}}
"""

GPIO_C = """{hdr}
#include <Uefi.h>
#include <Library/BaseLib.h>
#include <Library/GpioTableLib.h>

GPIO_CFG  *mGpioCfgTable;
UINT32    mGpioCfgTableLength;

GPIO_CFG  GpioCfgTable[] = {{
{rows}
}};

RETURN_STATUS
EFIAPI
GpioTableLibConstructor (
  VOID
  )
{{
  mGpioCfgTable       = GpioCfgTable;
  mGpioCfgTableLength = ARRAY_SIZE (GpioCfgTable);

  return RETURN_SUCCESS;
}}
"""

INF = """## @file
#  {what} for {board} (generated by scripts/extract/gen_iolibs.py).
#
#  SPDX-License-Identifier: BSD-2-Clause-Patent
##

[Defines]
  INF_VERSION                    = 0x0001001A
  BASE_NAME                      = {lib}
  FILE_GUID                      = {guid}
  MODULE_TYPE                    = BASE
  VERSION_STRING                 = 1.0
  LIBRARY_CLASS                  = {lib}
  CONSTRUCTOR                    = {lib}Constructor

[Sources]
  {lib}.c

[Packages]
  MdePkg/MdePkg.dec
  Silicon/CIX/Sky1/CixPkg.dec
  Platform/CIX/Sky1/Sky1.dec

[LibraryClasses]
  BaseLib
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--image", required=True)
    ap.add_argument("--start", default="0x3FE000")
    ap.add_argument("--board", required=True, help="human readable board name")
    ap.add_argument("--ioconfig", required=True)
    ap.add_argument("--out", required=True, help="board Library/ directory")
    ap.add_argument("--source-name", help="vendor file name to record (defaults to the image file name)")
    a = ap.parse_args()

    img = Path(a.image)
    sha = hashlib.sha256(img.read_bytes()).hexdigest()
    pm, gp = find_tables(str(img), int(a.start, 0))
    names = io_names(Path(a.ioconfig).read_text())
    out = Path(a.out)
    for lib, what, tmpl, rows in (
        ("PinMuxTableLib", "Pin multiplexing table", PINMUX_C, "\n".join(pinmux_lines(pm, names))),
        ("GpioTableLib", "GPIO configuration table", GPIO_C, "\n".join(gpio_lines(gp))),
    ):
        d = out / lib
        d.mkdir(parents=True, exist_ok=True)
        hdr = HDR.format(what=what, board=a.board, src=a.source_name or img.name, sha=sha)
        (d / f"{lib}.c").write_text(tmpl.format(hdr=hdr, rows=rows))
        guid = str(uuid.uuid5(uuid.NAMESPACE_URL, f"edk2-cix/{a.board}/{lib}")).upper()
        (d / f"{lib}.inf").write_text(INF.format(what=what, board=a.board, lib=lib, guid=guid))
        print(f"{d}: {len(pm) if lib.startswith('Pin') else len(gp)} entries")


if __name__ == "__main__":
    main()
