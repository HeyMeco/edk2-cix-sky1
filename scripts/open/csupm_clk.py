"""Write the open CSU_PM firmware's clock-tree types and tables from CIX's
image (its DWARF and initialised data).

  csupm_clk.py CIX_ELF OUTDIR

OUTDIR/clk_cix.h   the clock tree's types as CIX's compiler laid them out
                   (dwarf_header.py), FreeRTOS handles as plain pointers
OUTDIR/clk_data.c  the tables: the 358 clock nodes (topology, register
                   fields, power-on settings), mux sources, PLL descriptors,
                   pixel PLL nodes, the nodes exported to SCMI

The tables are the image's initial values; what CIX's firmware fills in at
run time (tree links, PLL pointers, rates) the open firmware fills in too.
"""

import struct
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from dwarf_dump import Dwarf, Printer, die_name, find_type, size_of, strip  # noqa: E402

HERE = Path(__file__).resolve().parent
TYPES = {0: "CLK_TYPE_ROOT", 1: "CLK_TYPE_PLL", 2: "CLK_TYPE_PLL_VCO", 3: "CLK_TYPE_PLL_POSTDIV",
         4: "CLK_TYPE_DIV", 5: "CLK_TYPE_FIXED_DIV", 6: "CLK_TYPE_GATE", 7: "CLK_TYPE_MUX",
         8: "CLK_TYPE_CUSTOM"}
HEADER = """/* SPDX-License-Identifier: BSD-2-Clause-Patent */
/*
 * Generated by scripts/open/csupm_clk.py from CIX's CSU_PM image ({what}).
 * Do not edit; change the generator.
 */
"""


def clk_enum(dw):
    for cu in dw.dw.iter_CUs():
        for d in cu.iter_DIEs():
            if d.tag == "DW_TAG_typedef" and die_name(d) == "CLK_TREE_ENUM_IDX":
                e = d.get_DIE_from_attribute("DW_AT_type")
                return {c.attributes["DW_AT_const_value"].value: die_name(c)
                        for c in e.iter_children() if c.tag == "DW_TAG_enumerator"}
    raise SystemExit("no CLK_TREE_ENUM_IDX")


def header(elf, out):
    txt = subprocess.run([sys.executable, str(HERE / "dwarf_header.py"), elf, "pllmgmt/", "clktree/",
                          "--only-types"], check=True, capture_output=True, text=True).stdout
    drop = ("_Uint32t", "uint32_t", "uint16_t", "uint8_t", "_ULonglong", "uint64_t", "_Int32t",
            "int32_t", "_Sizet", "size_t", "QueueHandle_t", "TaskHandle_t", "TickType_t",
            "BaseType_t", "UBaseType_t")
    lines, skip = [], False
    for line in txt.splitlines():
        s = line.strip()
        if s.startswith("struct ") and s.endswith(";") and "{" not in s:
            continue                                    # forward declarations
        if s.startswith("typedef") and s.endswith(";") and any(s.endswith(f" {d};") or s.endswith(f"*{d};")
                                                               for d in drop):
            continue
        if s.startswith("struct QueueDefinition") or s.startswith("struct tskTaskControlBlock") \
                or s.startswith("typedef QueueHandle_t SemaphoreHandle_t"):
            continue
        lines.append(line.replace("SemaphoreHandle_t", "void *").replace("TaskHandle_t", "void *")
                     .replace("void * xSemph", "void *xSemph").replace("void * tskHandle", "void *tskHandle"))
    body = "\n".join(lines)
    while "\n\n\n" in body:
        body = body.replace("\n\n\n", "\n\n")
    body = body.replace("typedef struct tree_node TREE_NODE;", "")
    body = body.replace("struct tree_node {", "typedef struct tree_node TREE_NODE;\n\nstruct tree_node {", 1)
    (out / "clk_cix.h").write_text(
        HEADER.format(what="DWARF of pllmgmt/ and clktree/") +
        "#ifndef CLK_CIX_H\n#define CLK_CIX_H\n\n#include <stdbool.h>\n#include <stddef.h>\n"
        "#include <stdint.h>\n\n" + body.strip() + "\n\n#endif\n")


def node_init(dw, names, raw, i):
    name_p, c0, c1, df, af, rates, u0, u1, u2, u3 = struct.unpack_from("<10I", raw, 0)
    nm = dw.read(name_p, 48).split(b"\0")[0].decode() if name_p else None
    t = (c0 >> 19) & 15
    f = [f'\t\t.name = "{nm}",' if nm else "\t\t.name = NULL,",
         f"\t\t.mass_ctrl0 = {c0:#x},\t/* parent {names.get(c0 & 0x1ff, c0 & 0x1ff)}, {TYPES.get(t, t)} */"]
    if c1:
        f.append(f"\t\t.mass_ctrl1 = {c1:#x},")
    if df:
        f.append(f"\t\t.desired_freq = {df},")
    if af:
        f.append(f"\t\t.actual_freq = {af},")
    assert rates == 0, (i, rates)
    if t in (1, 2, 3):
        assert u0 == 0
        if u1:
            f.append(f"\t\t.cfg_idx = {u1},")
    elif t == 4:
        f.append(f"\t\t.duty_div = {{ .div_reg = {u0:#x}, .div_mask = {u1:#x}, "
                 f".div_bitmap = {u2:#x}, .attr = {u3:#x} }},")
    elif t == 5:
        f.append(f"\t\t.fixed_div = {{ .div_factor = {u0} }},")
    elif t == 6:
        f.append(f"\t\t.gate = {{ .reg = {u0:#x}, .mask = {u1:#x}, .attr = {u2:#x} }},")
        assert u3 == 0
    elif t == 7:
        src = f", .src_clk = {dw.sym_at[u2][0]}" if u2 else ""
        f.append(f"\t\t.mux = {{ .reg = {u0:#x}, .mask = {u1:#x}{src}, .attr = {u3:#x} }},")
    elif t == 8:
        fn = dw.sym_at[u0][0]
        f.append(f"\t\t.cus = {{ .opr = {fn}, .params = (void *){u1}, .por_freq = {u2}, .attr = {u3:#x} }},")
    else:
        assert (u0, u1, u2, u3) == (0, 0, 0, 0), (i, t)
    return "{\n" + "\n".join(f) + "\n\t}"


def generic(dw, name, fixups=()):
    """A variable through dwarf_dump's printer, anonymous unions flattened."""
    addr, die = dw.vars[name]
    t = die.get_DIE_from_attribute("DW_AT_type")
    p = Printer(dw, 0)
    txt = p.object(name, addr, t, size_of(t))
    # '.<anon> = { .x = v }' -> '.x = v'
    import re
    txt = re.sub(r"\.<anon> = \{ \.(\w+) = ([^{}]*?) \}", r".\1 = \2", txt)
    for a, b in fixups:
        txt = txt.replace(a, b)
    return txt


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    elf, out = sys.argv[1], Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    header(elf, out)
    dw = Dwarf(elf)
    names = clk_enum(dw)
    base, _ = dw.vars["clk_tree_st"]
    n = 358
    raw = dw.read(base, 68 * n)
    nodes = [f"\t[{names[i]}] = " + node_init(dw, names, raw[68 * i:68 * (i + 1)], i) + ","
             for i in range(n)]
    pbase, _ = dw.vars["g_pixel_mux_nodes"]
    praw = dw.read(pbase, 68 * 8)
    pix = [f"\t[{i}] = " + node_init(dw, names, praw[68 * i:68 * (i + 1)], i) + "," for i in range(8)]
    exp = struct.unpack_from("<273H", dw.read(dw.vars["clk_nodes_export_to_os"][0], 546))
    src = struct.unpack_from("<6H", dw.read(dw.vars["g_pixel_src"][0], 12))
    postdiv = dw.read(dw.vars["_s_postdiv"][0], 25)
    mux = []
    mraw = dw.read(dw.vars["g_mux_src"][0], 14 * 12)
    for k in range(12):
        idx, *s = struct.unpack_from("<7H", mraw, 14 * k)
        mux.append(f"\t{{ .idx = {names[idx]}, .src_clk = {{ {', '.join(names.get(x, str(x)) if x else '0' for x in s)} }} }},")
    fix = [(f"CLK_TREE_ENUM_IDX ", "CLK_TREE_ENUM_IDX "), ("PLL_CTRL_POLICY[23] pll_dev", "PLL_CTRL_POLICY pll_dev[23]"),
           ("PLL_CTRL_POLICY[6] pll_post", "PLL_CTRL_POLICY pll_post[6]")]
    pd = generic(dw, "pll_dev", fix)
    pp = generic(dw, "pll_post", fix)
    import re
    for v in ("pd", "pp"):
        s = locals()[v]
        s = re.sub(r"\.xSemph = [^,]*,", ".xSemph = NULL,", s)
        s = s.replace("\t\t.pll_st = PLL_HSM_STABLE_RUNNING,", "\t\t.pll_st = PLL_HSM_INIT,")
        if v == "pd":
            pd = s
        else:
            pp = s
    text = HEADER.format(what="initialised data of clk_nodes.c, pll_mux.c, pll_policy.c, pll_pixel_mux.c,"
                         "\n * clk_nodes_scmi.c, pll_freq.c") + \
        '#include "clk.h"\n\n' + \
        "CLK_TREE_STRUCT clk_tree_st[CLK_TREE_MAX_IDX] = {\n" + "\n".join(nodes) + "\n};\n\n" + \
        "CLK_TREE_STRUCT g_pixel_mux_nodes[8] = {\n" + "\n".join(pix) + "\n};\n\n" + \
        "uint16_t g_pixel_src[6] = { " + ", ".join(names.get(x, "0") if x else "0" for x in src) + " };\n\n" + \
        "CLK_MUX_SRC g_mux_src[12] = {\n" + "\n".join(mux) + "\n};\n\n" + \
        "/* SCMI clock i is node clk_nodes_export_to_os[i] */\n" + \
        "const uint16_t clk_nodes_export_to_os[273] = {\n" + \
        "".join(f"\t{names[x]},\n" for x in exp) + "};\n\n" + \
        "uint8_t _s_postdiv[25] = { " + ", ".join(str(b) for b in postdiv) + " };\n\n" + \
        "/* PLL state (pll_st, ts, targets, freq_*) is run time; CIX's image has it reset */\n" + \
        pd.replace("PLL_CTRL_POLICY pll_dev", "PLL_CTRL_POLICY pll_dev") + "\n" + pp + "\n"
    (out / "clk_data.c").write_text(text)


if __name__ == "__main__":
    main()
