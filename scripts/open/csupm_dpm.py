"""Write the open CSU_PM firmware's V/F and DVFS tables from CIX's image
(its initialised data).

  csupm_dpm.py CIX_ELF OUTFILE

OUTFILE (firmware/csupm/src/dpm/dpm_data.c) holds what CIX's
config_dvfs.c, cfg_dpm.c, cfg_pwr.c, cfg_fuse.c and subsys_hsm.c start
with: the OPP tables of every DVFS domain (the MP tables CIX picks from
for production parts, the test tables for engineering samples), the
frequency limits per part (opp_limit), the power maps the OPPs' power
comes from (U_PWR_COEF_MAP per domain, measured power per frequency),
the DVFS element to clock/DxS/EDP map, each board layout's OPP maxima
and the eFuse bit offsets of the V/F curves.  They are the image's
initial values: what CIX's firmware changes at run time (OPP voltages
and levels, maxima), the open firmware changes too.
"""

import struct
import sys
from pathlib import Path

from elftools.elf.elffile import ELFFile

HEADER = """/* SPDX-License-Identifier: BSD-2-Clause-Patent */
/*
 * Generated by scripts/open/csupm_dpm.py from CIX's CSU_PM image (initialised
 * data of config_dvfs.c, cfg_dpm.c, cfg_pwr.c, cfg_fuse.c, subsys_hsm.c).
 * Do not edit; change the generator.
 */
#include "dpm.h"
"""

# OPP tables: MP (production) tables per CPU cluster and DSU, then the
# test tables, then the fixed domains' tables
MP_TABLES = [
    ["mp_lit_c0123_tpl_static", "mp_lit_c0123_base_dvfs", "mp_lit_c0123_base_dvfs", "mp_lit_c0123_base_dvfs"],
    ["mp_gb0_c89_tpl_static", "mp_gb0_c89_vmin_dvfs", "mp_gb0_c89_fused_dvfs", "mp_gb0_c89_vmin_dvfs"],
    ["mp_gb1_cab_tpl_static", "mp_gb1_cab_vmin_dvfs", "mp_gb1_cab_fused_dvfs", "mp_gb1_cab_vmin_dvfs"],
    ["mp_gm0_c45_tpl_static", "mp_gm0_c45_vmin_dvfs", "mp_gm0_c45_fused_dvfs", "mp_gm0_c45_mp2_dvfs"],
    ["mp_gm1_c67_tpl_static", "mp_gm1_c67_vmin_dvfs", "mp_gm1_c67_fused_dvfs", "mp_gm1_c67_vmin_dvfs"],
    ["mp_dsu_base_static", "mp_dsu_base_dvfs", "mp_dsu_base_dvfs", "mp_dsu_base_dvfs"],
]
FIXED = ["gpu_core_opp_perf", "gpu_top_opp_perf", "gpu_core_opp_budget", "gpu_top_opp_budget",
         "npu_opp", "vpu_opp", "ci700_opp", "mmhub_opp"]
PWR_MAPS = ["cpu_lit_pwr", "cpu_mid0_pwr", "cpu_mid1_pwr", "cpu_big0_pwr", "cpu_big1_pwr",
            "dsu_pwr", "gpu_pwr", "dummy_pwr"]


class Image:
    def __init__(self, path):
        self.elf = ELFFile(open(path, "rb"))
        self.sym = {}
        self.at = {}
        dup = set()
        for s in self.elf.get_section_by_name(".symtab").iter_symbols():
            if s["st_info"]["type"] != "STT_OBJECT" or not s.name:
                continue
            if s.name in self.sym:
                dup.add(s.name)
            self.sym[s.name] = (s["st_value"], s["st_size"])
            if s["st_value"] not in self.at or self.at[s["st_value"]].startswith("."):
                self.at[s["st_value"]] = s.name
        self.dup = dup

    def addr(self, name):
        assert name not in self.dup, name
        return self.sym[name]

    def read(self, a, n):
        for seg in self.elf.iter_segments():
            if seg["p_type"] == "PT_LOAD" and seg["p_vaddr"] <= a < seg["p_vaddr"] + seg["p_memsz"]:
                o = a - seg["p_vaddr"]
                data = seg.data() + bytes(seg["p_memsz"] - seg["p_filesz"])
                return data[o:o + n]
        raise KeyError(hex(a))

    def var(self, name, fmt):
        a, n = self.addr(name)
        k = struct.calcsize("<" + fmt)
        return struct.unpack("<" + fmt * (n // k), self.read(a, n // k * k))

    def string(self, a):
        return self.read(a, 64).split(b"\0")[0].decode()


def fl(x):
    """A float as a C literal that reads back to the same single."""
    s = f"{x:.9g}"
    if "e" not in s and "." not in s:
        s += ".0"
    return s + "f"


def opp_array(img, name):
    v = img.var(name, "4I")
    n = len(v) // 4
    rows = []
    for i in range(n):
        lv, vo, fr, pw = v[4 * i:4 * i + 4]
        if (lv, vo, fr, pw) == (0, 0, 0, 0):
            rows.append("\t{ 0 },")
        else:
            rows.append(f"\t{{ .level = {lv}, .voltage = {vo}, .frequency = {fr}, .power = {pw} }},")
    return f"struct mod_dvfs_opp {name}[{n}] = {{\n" + "\n".join(rows) + "\n};\n"


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    img = Image(sys.argv[1])
    out = [HEADER]

    # --- OPP tables ---------------------------------------------------------
    test_ptr = img.var("test_opp_tables", "I")
    test = [[img.at[p] for p in test_ptr[9 * d:9 * d + 9]] for d in range(6)]
    mp_ptr = img.var("mp_opp_tables", "I")
    assert [[img.at[p] for p in mp_ptr[4 * d:4 * d + 4]] for d in range(6)] == MP_TABLES
    names = []
    for row in MP_TABLES + test:
        for n in row:
            if n not in names:
                names.append(n)
    names += FIXED
    out.append("\n/* --- OPP tables (struct mod_dvfs_opp: level, mV, kHz, mW) --- */\n")
    out.append("/* level is the frequency in MHz until create_element_table standardises it;\n"
               " * a zero frequency, voltage or power is filled in from the level and the\n"
               " * power maps (dvfs_patch_opp_table) */\n\n")
    for n in names:
        out.append(opp_array(img, n) + "\n")

    def table(name, rows, cols):
        out.append(f"struct mod_dvfs_opp *const {name}[{len(rows)}][{cols}] = {{\n")
        for r in rows:
            out.append("\t{ " + ", ".join(r) + " },\n")
        out.append("};\n\n")

    out.append("/* allocate_config_dvfs_opp_tables: per cluster (lit, gb0, gb1, gm0, gm1, dsu),\n"
               " * one table per selector */\n")
    table("mp_opp_tables", MP_TABLES, 4)
    table("test_opp_tables", test, 9)
    for nm, cnt in (("mp_opp_tab_name", 4), ("test_opp_tab_name", 9)):
        s = [img.string(p) for p in img.var(nm, "I")]
        assert len(s) == cnt
        out.append(f"const char *const {nm}[{cnt}] = {{ " + ", ".join(f'"{x}"' for x in s) + " };\n")

    # --- OPN limits -----------------------------------------------------------
    lim = img.var("opp_limit", "H")
    assert len(lim) == 130
    out.append("\n/* subsys_hsm.c: highest level (MHz) per DxS domain, by g_opp_limit_selector */\n")
    out.append("const uint16_t opp_limit[10][DPM_DxS_MAX] = {\n")
    for r in range(10):
        out.append("\t{ " + ", ".join(str(x) for x in lim[13 * r:13 * r + 13]) + " },\n")
    out.append("};\n")

    # --- board layouts: OPP maxima ---------------------------------------------
    a, n = img.addr("dpm_edp_scheme")
    assert n == 8 * 92
    out.append("\n/* cfg_dpm.c dpm_edp_scheme[].opp_max: highest level per DxS domain, by board\n"
               " * layout (the rails are src/pmic.c's) */\n")
    out.append("uint16_t dpm_edp_opp_max[DPM_EDP_CFG_MAX][DPM_DxS_MAX] = {\n")
    for t in range(8):
        v = struct.unpack("<13H", img.read(a + 92 * t, 26))
        out.append("\t{ " + ", ".join(str(x) for x in v) + " },\n")
    out.append("};\n")

    # --- maps -------------------------------------------------------------------
    m = img.var("dvfs_elem_id_map_tab", "HBB")
    out.append("\n/* config_dvfs.c: DVFS element -> clock tree node, DxS and EDP domain */\n")
    out.append("const struct dvfs_elem_id_map_tab dvfs_elem_id_map_tab[DVFS_ELEMENT_IDX_COUNT] = {\n")
    for i in range(12):
        out.append(f"\t{{ .clk_id = {m[3 * i]}, .dxs_id = {m[3 * i + 1]}, .edp_id = {m[3 * i + 2]} }},\n")
    out.append("};\n")
    v = img.var("dpm_dxs_to_dvfs_elem_map", "B")
    out.append("\n/* cfg_dpm.c: DxS domain <-> DVFS element */\n")
    out.append("const uint8_t dpm_dxs_to_dvfs_elem_map[12] = { " + ", ".join(str(x) for x in v) + " };\n")
    v = img.var("dpm_dvfs_elem_to_dxs_map", "B")
    out.append("const uint8_t dpm_dvfs_elem_to_dxs_map[12] = { " + ", ".join(str(x) for x in v) + " };\n")
    v = img.var("dpm_edp_to_elem_map", "BxxxI")
    out.append("\n/* cfg_dpm.c: EDP domain -> first DPM element (core) and how many */\n")
    out.append("const DPM_EDP_TO_ELEM_MAP dpm_edp_to_elem_map[DPM_EDP_MAX] = {\n")
    for i in range(8):
        out.append(f"\t{{ .elem0 = {v[2 * i]}, .elem_num = {v[2 * i + 1]} }},\n")
    out.append("};\n")

    # --- power ------------------------------------------------------------------
    out.append("\n/* cfg_pwr.c: power maps (kHz, dynamic coefficient, mV, static mW, dynamic mW\n"
               " * computed by u_pwr_initMap) */\n")
    for nm in PWR_MAPS:
        a, n = img.addr(nm)
        k = n // 20
        out.append(f"U_PWR_COEF_MAP {nm}[{k}] = {{\n")
        for i in range(k):
            fk, c, mv, st, dy = struct.unpack("<IfIff", img.read(a + 20 * i, 20))
            out.append(f"\t{{ {fk}, {fl(c)}, {mv}, {fl(st)}, {fl(dy)} }},\n")
        out.append("};\n")
    sizes = img.var("dxs_pwrmap_size", "B")
    ptrs = img.var("dxs_pwrmap_ptr", "I")
    out.append("U_PWR_COEF_MAP *const dxs_pwrmap_ptr[DPM_DxS_MAX] = { " +
               ", ".join(img.at[p] for p in ptrs) + " };\n")
    out.append("const uint8_t dxs_pwrmap_size[DPM_DxS_MAX] = { " + ", ".join(str(x) for x in sizes) + " };\n")
    for nm in ("dpm_freq2pwr_opp_table_coef", "dpm_freq2pwr_util_coef"):
        out.append(f"const float {nm}[DPM_DxS_MAX] = {{ " +
                   ", ".join(fl(x) for x in img.var(nm, "f")) + " };\n")
    md = img.var("measured_data", "HH")
    out.append("\n/* config_dvfs.c: measured power (MHz, mW) per DxS domain, highest first */\n")
    out.append("const pwr_data_t measured_data[8][7] = {\n")
    for d in range(8):
        out.append("\t{ " + ", ".join(f"{{ {md[14 * d + 2 * i]}, {md[14 * d + 2 * i + 1]} }}"
                                      for i in range(7)) + " },\n")
    out.append("};\n")

    # --- fuses ------------------------------------------------------------------
    out.append("\n/* cfg_fuse.c: V/F data in the eFuse copy, by bit offset (patch points for\n"
               " * GB0 and GM1, then the curves of GM0, GM1, GB0, GB1) */\n")
    out.append("VF_FUSE_DATA core_vf_fuse[6] = {\n")
    for nm in ("core_vf_patch", "core_vf_curve"):
        v = img.var(nm, "8H")
        for i in range(len(v) // 8):
            assert not any(v[8 * i + 1:8 * i + 8])
            out.append(f"\t{{ .bit_offset = {v[8 * i]:#x} }},\n")
    out.append("};\n")
    out.append("const uint16_t bit_offsets[9] = { " + ", ".join(f"{x:#x}" for x in img.var("bit_offsets", "H")) + " };\n")
    out.append("const uint16_t gpu_bit_offsets[3] = { " +
               ", ".join(f"{x:#x}" for x in img.var("gpu_bit_offsets", "H")) + " };\n")

    Path(sys.argv[2]).write_text("".join(out))


if __name__ == "__main__":
    main()
