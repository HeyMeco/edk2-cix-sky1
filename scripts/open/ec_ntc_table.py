"""The NTC table for firmware/ec: the vendor EC's own conversion routine
(bank 1 0xDD46: ADC code -> float degrees C, Beta 4250, 100K NTC under a
24K pull-up, 3.3 V, 10-bit) run in the emulator for every ADC code, then
truncated as the vendor does (whole degrees for the comparisons, tenths
for the values it writes to CSU_PM).  Writes firmware/ec/src/ntc_table.h."""
import struct, sys
from ec_emu import EC, NullBoard, ADC_DATA

img = open(sys.argv[1], 'rb').read()
out = sys.argv[2]

class Fixed(NullBoard):
    code = 0
    def read(self, a):
        lo, hi = ADC_DATA[0]
        if a == lo: return self.code & 0xFF
        if a == hi: return self.code >> 8
        return None

b = Fixed()
ec = EC(img, b)
ec.run(120)                     # past the C start-up (RAM, init data)
c = ec.cpu
RET = 0xFFF0
vals = []
for code in range(1024):
    b.code = code
    c.sfr[0x81] = 0x30          # stack
    c.sfr[0x90] = (c.sfr[0x90] & 0xF8) | 1   # bank 1
    c.push(RET & 0xFF); c.push(RET >> 8)
    c.pc = 0xDD46
    c.iram[7] = 0               # R7 = channel 0 (bank 0 registers)
    c.sfr[0xD0] = 0
    c.sfr[0xA8] = 0             # no interrupts
    ec.cpu.in_isr = []
    n = 0
    while c.pc != RET:
        c.step(); n += 1
        if n > 2000000: raise SystemExit('stuck at %04X' % c.pc)
    f = struct.unpack('>f', bytes(ec.x[0x9638:0x963C]))[0]
    vals.append(f)
import numpy as np
deg = []
for f in vals:
    c = float(np.float32(f) + np.float32(-273.5))   # the vendor's FADD
    if c != c or abs(c) > 1e6:
        c = 0.0
    d = int(c)                                     # truncation, as its float->int
    t = int((c - d) * 10) if c >= 0 else 0
    deg.append((max(-128, min(127, d)), t))
with open(out, 'w') as fh:
    fh.write('/* SPDX-License-Identifier: BSD-2-Clause-Patent */\n')
    fh.write('/* generated by scripts/open/ec_ntc_table.py from the vendor EC\'s own\n')
    fh.write(' * conversion: ADC code -> degrees C (truncated), tenths */\n')
    fh.write('static __code const int8_t ntc_deg[1024] = {\n')
    for i in range(0, 1024, 16):
        fh.write('\t' + ', '.join('%d' % d for d, _ in deg[i:i+16]) + ',\n')
    fh.write('};\nstatic __code const uint8_t ntc_tenth[1024] = {\n')
    for i in range(0, 1024, 16):
        fh.write('\t' + ', '.join('%d' % t for _, t in deg[i:i+16]) + ',\n')
    fh.write('};\n')
print('C:', [round(float(np.float32(vals[c]) + np.float32(-273.5)), 3) for c in (0x284, 0x2b6, 0x2e5, 0x2c9, 0x2f7, 0x2db)])
for code in (0x284, 0x2b6, 0x2e5, 0x2c9, 0x2f7, 0x2db, 0, 1, 1022, 1023):
    print(hex(code), vals[code], deg[code])
