"""Write the SE firmware's PVT table from CIX's SE debug ELF.

  se_pvt_table.py SE_ELF OUTFILE [--check]

OUTFILE (firmware/se/driver/pvt_data.c) holds g_soc_pvt_data, CIX's
table of measured dies (driver/vf_sel/drv_pvt_ll.h in CIX's tree, 2668
words in .rodata): one word per die, wafer number, die position and the
die's PVT (process) ring-oscillator average, which drv_pvt_get_vf_ver
(firmware/se/driver/pvt.c) looks up for early dies whose eFuse carries no
average.  Each word is wafer[5:0], x[13:6], y[21:14], average[31:22];
the generated file spells the fields out and keeps CIX's order.  --check
compares an existing OUTFILE with what would be written.
"""

import argparse
import struct
import sys
from pathlib import Path

from elftools.elf.elffile import ELFFile

NAME = "g_soc_pvt_data"
PER_LINE = 4

HEADER = """/* SPDX-License-Identifier: BSD-2-Clause-Patent */
/*
 * Generated by scripts/open/se_pvt_table.py from CIX's SE firmware debug
 * build (debug/se_fw/se_fw.elf, manifests/cix-debug-firmware.json):
 * g_soc_pvt_data of CIX's driver/vf_sel/drv_pvt_ll.h, {n} entries, in CIX's
 * order.  Do not edit; change the generator.
 *
 * Measured dies: wafer number, die position (x, y) and the die's PVT
 * ring-oscillator average, for early dies whose eFuse has no average
 * (drv_pvt_get_vf_ver, driver/pvt.c).  One word per die:
 * wafer[5:0], x[13:6], y[21:14], average[31:22].
 */
#include <stdint.h>

#define PVT(wafer, x, y, average) \\
	((uint32_t)(wafer) | (uint32_t)(x) << 6 | (uint32_t)(y) << 14 | (uint32_t)(average) << 22)

const uint32_t g_soc_pvt_data[{n}] = {{
"""


def table(elf_path):
    elf = ELFFile(open(elf_path, "rb"))
    sym = [s for s in elf.get_section_by_name(".symtab").iter_symbols()
           if s.name == NAME and s["st_info"]["type"] == "STT_OBJECT"]
    if len(sym) != 1:
        sys.exit(f"{NAME}: {len(sym)} symbols")
    addr, size = sym[0]["st_value"], sym[0]["st_size"]
    for s in elf.iter_sections():
        if s["sh_flags"] & 2 and s["sh_type"] != "SHT_NOBITS" and s["sh_addr"] <= addr < s["sh_addr"] + s["sh_size"]:
            data = s.data()[addr - s["sh_addr"]:addr - s["sh_addr"] + size]
            return struct.unpack(f"<{size // 4}I", data)
    sys.exit(f"{NAME} at {addr:#x} not in a loaded section")


def render(words):
    out = [HEADER.format(n=len(words))]
    for i in range(0, len(words), PER_LINE):
        row = []
        for w in words[i:i + PER_LINE]:
            row.append(f"PVT({w & 0x3f:2d}, {(w >> 6) & 0xff:2d}, {(w >> 14) & 0xff:2d}, {w >> 22:3d})")
        out.append("\t" + ", ".join(row) + ",\n")
    out.append("};\n")
    return "".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("elf")
    ap.add_argument("out")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render(table(a.elf))
    if a.check:
        if Path(a.out).read_text() != text:
            sys.exit(f"{a.out} differs from CIX's {NAME}")
        print(f"{a.out}: matches CIX's {NAME}")
        return
    Path(a.out).write_text(text)


if __name__ == "__main__":
    main()
